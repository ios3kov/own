#!/usr/bin/env python3
"""Prepare/restore synthetic document-preview data on an explicitly selected iOS simulator."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import sqlite3
import subprocess

parser=argparse.ArgumentParser()
parser.add_argument('action',choices=['seed','restore'])
parser.add_argument('--simulator',required=True)
parser.add_argument('--backup',type=Path,required=True)
args=parser.parse_args()
bundle='io.github.ios3kov.own'
root=Path(subprocess.check_output(['xcrun','simctl','get_app_container',args.simulator,bundle,'data'],text=True).strip())
# Refuse device paths and unrelated containers.
if '/CoreSimulator/Devices/' not in str(root): raise SystemExit('Not a simulator container')
subprocess.run(['xcrun','simctl','terminate',args.simulator,bundle],capture_output=True)
store=root/'Library/Application Support'/bundle/'RCTAsyncLocalStorage_V1'
manifest=store/'manifest.json'
key='local-llm-chat-storage'
chatfile=store/hashlib.md5(key.encode()).hexdigest()
dbpath=root/'Library/rag.db'
document=root/'Documents/own-qa-source.txt'
if args.action=='restore':
    saved=json.loads((args.backup/'identity.json').read_text())
    # Xcode may migrate this simulator's sandbox during reinstall. Confirm the
    # precise fixture before touching the new location; never guess by filename.
    passage='Own QA source: the meeting starts at 14:30 in room Cedar. This is synthetic test data.'
    if not document.is_file() or document.read_text()!=passage:
        raise SystemExit('Synthetic document changed or missing; preserve backup')
    with sqlite3.connect(dbpath) as db:
        record=db.execute('SELECT project_id,name,path FROM rag_documents WHERE id=?',(saved['documentId'],)).fetchone()
    expected_path=str(Path(saved['container'])/'Documents/own-qa-source.txt')
    if record!=('own-qa-document-project','Own QA notes.txt',expected_path):
        raise SystemExit('Synthetic document identity changed; preserve backup')
    shutil.copyfile(args.backup/'manifest.json',manifest)
    if saved['chatfile']:shutil.copyfile(args.backup/'chatfile',chatfile)
    elif chatfile.exists():chatfile.unlink()
    with sqlite3.connect(dbpath) as db:
        db.execute('DELETE FROM rag_documents WHERE id=? AND project_id=?',(saved['documentId'],'own-qa-document-project'))
    document.unlink(missing_ok=True)
    print('Restored original simulator preferences; removed only the synthetic document record/file')
else:
    if args.backup.exists():raise SystemExit('Backup already exists; restore it before another run')
    if document.exists():raise SystemExit('Fixture path already exists; refusing to overwrite')
    args.backup.mkdir(parents=True)
    shutil.copyfile(manifest,args.backup/'manifest.json')
    if chatfile.exists():shutil.copyfile(chatfile,args.backup/'chatfile')
    prefs=json.loads(manifest.read_text())
    raw=prefs.get(key)
    state=json.loads(raw if isinstance(raw,str) else chatfile.read_text()) if raw is not None or chatfile.exists() else {'state':{'conversations':[]},'version':0}
    passage='Own QA source: the meeting starts at 14:30 in room Cedar. This is synthetic test data.'
    document.write_text(passage)
    with sqlite3.connect(dbpath) as db:
        result=db.execute('INSERT INTO rag_documents (project_id,name,path,size,created_at,enabled) VALUES (?,?,?,?,?,1)',('own-qa-document-project','Own QA notes.txt',str(document),len(passage),'2026-10-24T00:00:00Z'))
        docid=result.lastrowid
    (args.backup/'identity.json').write_text(json.dumps({'container':str(root),'documentId':docid,'chatfile':chatfile.exists()}))
    source={'projectId':'own-qa-document-project','documentId':docid,'name':'Own QA notes.txt','part':1,'excerpt':passage}
    conversation={'id':'own-qa-source-chat','title':'Own QA document sources','modelId':'apple-foundation-models','createdAt':'2026-10-24T23:00:00Z','updatedAt':'2026-10-24T23:00:00Z','projectId':'own-qa-document-project','messages':[{'id':'qa-user','role':'user','content':'When is the meeting?','timestamp':1},{'id':'qa-assistant','role':'assistant','content':'The meeting starts at 14:30 in room Cedar.','timestamp':2,'generationMeta':{'gpu':False,'documentSources':[source]}}]}
    state['state']['conversations']=[c for c in state['state']['conversations'] if c['id']!=conversation['id']]+[conversation]
    state['state']['activeConversationId']=conversation['id']
    prefs[key]=json.dumps(state)
    manifest.write_text(json.dumps(prefs))
    print('Prepared synthetic persisted source preview; no model reply has been generated by this fixture')
